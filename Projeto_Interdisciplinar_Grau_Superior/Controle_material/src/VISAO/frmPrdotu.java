private void listarValores(){
    try {
        ProdutoDAO objprodutoDAO = new ProdutoDAO();
        
        DefaultTableModel model = (DefaultTableModel) tabelaproduto.getModel();
        model.setNumRows(0);
        
        ArrayList<ProdutoDTO>lista = objprodutoDAO.PesquisarProduto();
        
        for(int num = 0; num <lista.size(); num++){
            model.addRow(new Object[]{
                lista.get(num).getId_material(),
                lista.get(num).getNome_material(),
                lista.get(num).getDescricao_material(),
                lista.get(num).getQuantidade_material()
                
                
            });
        }
        
    } catch (Exception erro) {
        
        JOptionPane.showMessageDialog(null,"Lista valores " + erro);
    }
}

private void CarregaCampos(){
    int setar = tabelaproduto.getSelectedRow();
    
    txtCodigo.setText(tabelaproduto.getModel().getValueAt(setar, 0).toString());
    txtNome.setText(tabelaproduto.getModel().getValueAt(setar, 1).toString());
    txtDescricao.setText(tabelaproduto.getModel().getValueAt(setar, 2).toString());
    txtUnidade.setText((tabelaproduto).getModel().getValueAt(setar,3).toString());
            
}

private void cadastrarProduto(){
        String nome, descricao;
        int unidade;
        nome= txtNome.getText();
        descricao = txtDescricao.getText();
        unidade = Integer.parseInt(txtUnidade.getText());
        ProdutoDTO objprodutodto = new ProdutoDTO();
        objprodutodto.setNome_material(nome);
        objprodutodto.setDescricao_material(descricao);
        objprodutodto.setQuantidade_material(unidade);
        ProdutoDAO objprodutodao = new ProdutoDAO();
        objprodutodao.cadastrarProduto(objprodutodto);
        
}

  private void LimparCampos(){
      txtCodigo.setText("");
      txtNome.setText("");
      txtDescricao.setText("");
      txtUnidade.setText("");
      txtNome.requestFocus();
  }
  
  private void AlterarProduto(){
      int id_produto, unidade;
      String nome, descricao;
      
      id_produto = Integer.parseInt(txtCodigo.getText());
      nome = txtNome.getText();
      descricao = txtDescricao.getText();
      unidade = Integer.parseInt(txtUnidade.getText());
      
      ProdutoDTO objprodutodto = new ProdutoDTO();
      objprodutodto.setId_material(id_produto);
      objprodutodto.setNome_material(nome);
      objprodutodto.setDescricao_material(descricao);
      objprodutodto.setQuantidade_material(unidade);
      
      ProdutoDAO objprodutodao = new ProdutoDAO();
      objprodutodao.alterarProduto(objprodutodto);
       
  }
  
  private void ExcluirProduto(){
      int id_produto;
      
      id_produto = Integer.parseInt(txtCodigo.getText());
      
      ProdutoDTO objProdutodto = new ProdutoDTO();
      objProdutodto.setId_material(id_produto);
      
      ProdutoDAO objprodutodao = new ProdutoDAO();
      objprodutodao.excluirProduto(objProdutodto);
  }
  
  private void adicionarProduto(){
      ProdutoDTO dto = new ProdutoDTO();
      
      dto.setId_material(Integer.parseInt(txtCodigo.getText()));
      dto.setQuantidade_material(Integer.parseInt(txtUnidade.getText()));
       ProdutoDAO dao = new ProdutoDAO();
       dao.adicionarProduto(dto);
       
       JOptionPane.showMessageDialog(null,"Quantidade adicionada");
  }
  
  
  private void subtrairProduto(){
      ProdutoDTO dto = new ProdutoDTO();
      
      dto.setId_material(Integer.parseInt(txtCodigo.getText()));
      dto.setQuantidade_material(Integer.parseInt(txtUnidade.getText()));
      ProdutoDAO dao = new ProdutoDAO();
      dao.subtrairProduto(dto);
       
       JOptionPane.showMessageDialog(null,"Quantidade Subtraida");
  }
 
